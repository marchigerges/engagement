"""Builds guests.js: every invitation's names, so the greeting appears without waiting for Google.

Each entry is keyed by a hash of its link name and encrypted (AES-GCM) with a key derived from the
link name, so the file reveals nothing to anyone who doesn't already have that guest's link.

Input: a JSON file of [[link name, [guest names...]], ...], exported from the Sheet.
Usage:  python3 tools/make-guests.py invitations.json

New invitations added later still work without rebuilding: the site falls back to asking Google.
"""
import base64, hashlib, json, os, pathlib, sys

from cryptography.hazmat.primitives.ciphers.aead import AESGCM

root = pathlib.Path(__file__).resolve().parent.parent
rows = json.load(open(sys.argv[1]))
table = {}
for slug, names in rows:
    slug = slug.strip().lower()
    if not slug or not names:
        continue
    ident = hashlib.sha256(('id:' + slug).encode()).hexdigest()[:16]
    key = hashlib.sha256(('key:' + slug).encode()).digest()
    iv = os.urandom(12)
    sealed = AESGCM(key).encrypt(iv, json.dumps(names, ensure_ascii=False).encode(), None)
    table[ident] = base64.b64encode(iv + sealed).decode()

(root / 'guests.js').write_text(
    '// Generated by tools/make-guests.py. Encrypted guest names, one entry per invitation link.\n'
    'window.GUESTS = ' + json.dumps(table, separators=(',', ':')) + ';\n')
print('wrote guests.js with', len(table), 'invitations')
