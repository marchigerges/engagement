"""Builds 404.html from index.html.

GitHub Pages has no routing, so a personal link like /joseph-and-noura is served 404.html.
That file carries index.html's <head> tags (so link previews still show the card) and then
loads index.html in place, keeping the address bar on the guest's link.

Run after any change to index.html's <head>:  python3 tools/make-404.py
"""
import pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
index = (root / 'index.html').read_text()
head = re.search(r'<head>(.*?)</head>', index, re.S).group(1)
# Keep only the tags a link preview reads; the real page brings everything else.
keep = [l for l in head.splitlines() if re.match(r'\s*<(meta|title|link rel="icon")', l)]

page = '''<!doctype html>
<html lang="en-AU">
<head>
<!-- Generated by tools/make-404.py from index.html. Do not edit by hand. -->
__HEAD__
<style>html, body { margin: 0; background: #6a0000; }</style>
</head>
<body>
<script>
  fetch(new URL('index.html', location.href), { cache: 'no-cache' })
    .then(r => r.text())
    .then(html => { document.open(); document.write(html); document.close(); })
    .catch(() => { location.replace(new URL('./', location.href)); });
</script>
</body>
</html>
'''.replace('__HEAD__', '\n'.join(l.strip() for l in keep))
(root / '404.html').write_text(page)
print('wrote 404.html with', len(keep), 'head tags')
